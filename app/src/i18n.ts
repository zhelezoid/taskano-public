export type StringKey = keyof (typeof STRINGS)['ru'];

function resolveLang(lang: string | undefined | null): Lang {
  return lang && lang in STRINGS ? (lang as Lang) : 'en';
}

export function t(lang: string | undefined | null, key: StringKey, vars: Record<string, string | number> = {}): string {
  const dict = STRINGS[resolveLang(lang)];
  let s: string = dict[key] ?? STRINGS.en[key];
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

const LOCALE: Record<Lang, string> = { ru: 'ru-RU', tr: 'tr-TR', vi: 'vi-VN', en: 'en-GB' };

/** Разница в днях между датой срока и сегодняшним днём (локальным): <0 — срок прошёл. */
export function daysUntil(dueDate: string, today = new Date()): number {
  const d0 = new Date(today.getFullYear(), today.getMonth(), today.getDate()).getTime();
  const due = new Date(`${dueDate}T00:00:00`).getTime();
  return Math.round((due - d0) / 86400000);
}

/**
 * Когда оставлена реплика: «сегодня, 14:05», «вчера, 09:12», «28 сент., 17:40» (год — если не
 * текущий). Время — по часам телефона: карточку читают там, где человек сейчас.
 */
export function noteTime(lang: string | undefined | null, iso: string, now = new Date()): string {
  const d = new Date(iso);
  const locale = LOCALE[resolveLang(lang)];
  const time = d.toLocaleTimeString(locale, { hour: '2-digit', minute: '2-digit' });
  const local = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
  const n = daysUntil(local, now);
  if (n === 0) return `${t(lang, 'due_today')}, ${time}`;
  if (n === -1) return `${t(lang, 'note_yesterday')}, ${time}`;
  const day = d.toLocaleDateString(locale, d.getFullYear() === now.getFullYear()
    ? { day: 'numeric', month: 'short' } : { day: 'numeric', month: 'short', year: 'numeric' });
  return `${day}, ${time}`;
}

/** Дата с годом «21 окт. 2027 г.» — до какого числа действует токен агента. */
export function dayDate(lang: string | undefined | null, iso: string): string {
  return new Date(iso).toLocaleDateString(LOCALE[resolveLang(lang)], { day: 'numeric', month: 'short', year: 'numeric' });
}

/** Короткая дата «пн, 21 сент.» для даты проверки ожидания. */
export function shortDate(lang: string | undefined | null, iso: string): string {
  const d = new Date(iso);
  const local = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
  const n = daysUntil(local);
  if (n === 0) return t(lang, 'due_today');
  if (n === 1) return t(lang, 'due_tomorrow');
  return d.toLocaleDateString(LOCALE[resolveLang(lang)], { weekday: 'short', day: 'numeric', month: 'short' });
}

/**
 * Когда заходил — словами и днём, как их отдаёт сервер (спека person-presence): фраза уже посчитана
 * в поясе смотрящего, точного времени приложение не получает.
 */
export type SeenPhrase = string | null;

/** Что строка «Компания» знает о человеке, чтобы сказать, заходит ли он (спека person-presence). */
export interface SeenFacts {
  status: string;
  in_telegram: boolean;
  last_seen_bot: SeenPhrase;
  last_seen_bot_on: string | null;
  last_seen_app: SeenPhrase;
  last_seen_app_on: string | null;
  seen_tracked_since: string;
  joined_at: string | null;
}

/**
 * Строка «заходит ли человек» под его именем. Вошёл в бота, но приложения не открывал — говорим
 * именно это: там его дела, без приложения он видит их по одному. Но «ещё не заходил» — правда только
 * про того, кто пришёл после начала учёта (`seen_tracked_since`); про старожила отметки молчат лишь
 * с этой даты, и строка называет её, а не выдумывает «никогда». Иначе — последний заход по любому
 * каналу. Приглашённому, не принявшему, — ничего: он ещё не в компании.
 */
export function seenLabel(lang: string | undefined | null, p: SeenFacts): string | null {
  if (p.status !== 'active') return null;
  if (p.in_telegram && !p.last_seen_app) {
    const since = new Date(`${p.seen_tracked_since}T00:00:00Z`);
    if (p.joined_at && new Date(p.joined_at) >= since) return t(lang, 'app_never');
    const date = new Date(`${p.seen_tracked_since}T00:00:00`).toLocaleDateString(LOCALE[resolveLang(lang)], { day: 'numeric', month: 'short' });
    return t(lang, 'app_not_since', { date });
  }
  // Свежее из двух каналов: «в течение часа» свежее всего, дальше — по дню захода.
  const channels = [
    { phrase: p.last_seen_bot, on: p.last_seen_bot_on },
    { phrase: p.last_seen_app, on: p.last_seen_app_on },
  ].filter((c) => c.phrase && c.on);
  if (!channels.length) return null;
  const rank = (c: { phrase: SeenPhrase; on: string | null }) => `${c.phrase === 'within the last hour' ? '1' : '0'}${c.on}`;
  const latest = channels.reduce((a, b) => (rank(b) > rank(a) ? b : a));
  if (latest.phrase === 'within the last hour') return t(lang, 'seen_hour');
  if (latest.phrase === 'today') return t(lang, 'seen_today');
  if (latest.phrase === 'yesterday') return t(lang, 'seen_yesterday');
  const n = Number.parseInt(latest.phrase ?? '', 10);
  return Number.isFinite(n) ? t(lang, 'seen_days_ago', { n }) : null;
}

/**
 * Подпись срока. Без слова «просрочено» (философия проекта). `past` — срок прошёл: подпись мягко
 * подсвечивается, но без упрёка.
 */
export function dueLabel(lang: string | undefined | null, dueDate: string | null): { text: string; past: boolean; soon: boolean } | null {
  if (!dueDate) return null;
  const n = daysUntil(dueDate);
  if (n < 0) return { text: n === -1 ? t(lang, 'due_yesterday') : t(lang, 'due_days_ago', { n: -n }), past: true, soon: false };
  if (n === 0) return { text: t(lang, 'due_today'), past: false, soon: true };
  if (n === 1) return { text: t(lang, 'due_tomorrow'), past: false, soon: false };
  const date = new Date(`${dueDate}T00:00:00`);
  const opts: Intl.DateTimeFormatOptions = n < 7 ? { weekday: 'short', day: 'numeric', month: 'short' } : { day: 'numeric', month: 'short' };
  return { text: date.toLocaleDateString(LOCALE[resolveLang(lang)], opts), past: false, soon: false };
}

/**
 * Сколько человек проработал над взятым делом: прежние отрезки (`workedSeconds`) плюс идущий, от
 * `startedAt`. Идущий таймер, а не округлённая подпись: цифры должны бежать, иначе непонятно,
 * считает система или показывает что-то застывшее.
 *
 * До часа — «мм:сс», дальше «ч:мм:сс». Слов нет вовсе, поэтому и переводить нечего.
 * Отрицательная разница (часы устройства отстали от сервера) показывается нулём, а не «-3:00».
 */
export function elapsedLabel(startedAt: string, now: Date = new Date(), workedSeconds = 0): string {
  const started = new Date(startedAt).getTime();
  if (!Number.isFinite(started)) return '';
  // Прежние подходы плюс идущий: человек возвращается к делу не раз, и счётчик обязан показывать
  // всё потраченное на него время, а не последний отрезок.
  const total = Math.max(0, workedSeconds) + Math.max(0, Math.floor((now.getTime() - started) / 1000));
  const mm = String(Math.floor(total / 60) % 60).padStart(2, '0');
  const ss = String(total % 60).padStart(2, '0');
  const hours = Math.floor(total / 3600);
  return hours ? `${hours}:${mm}:${ss}` : `${mm}:${ss}`;
}

/**
 * Отработанное время словами: «45 мин», «3 ч», «12 ч 40 мин» (спека stats-page). Минуты приходят
 * целыми с сервера; дробь, если вдруг придёт, округляется, а не показывается «12,5 мин».
 */
export function durationLabel(lang: string | undefined | null, minutes: number): string {
  const total = Math.max(0, Math.round(minutes));
  const h = Math.floor(total / 60);
  const m = total % 60;
  if (!h) return t(lang, 'dur_min', { m });
  return m ? t(lang, 'dur_hm', { h, m }) : t(lang, 'dur_h', { h });
}
