-- Момент последнего «Взял» (спека mini-app): от него идёт таймер в приложении.
--
-- `started_at` для этого не годится: он ставится один раз, первым взятием, и по нему считается время
-- цикла дела (от «Взял» до «Готово», см. очередь). Если человек остановился и взялся снова, таймер
-- обязан пойти заново — а цикл обязан помнить, когда за дело сели впервые. Это два разных времени.
alter table tasks add column if not exists taken_at timestamptz;

comment on column tasks.taken_at is
  'Когда человек взял дело в последний раз — для таймера «в работе»; started_at остаётся первым взятием';

-- Делам, которые уже в работе, проставляем то, что есть: иначе у них таймер начнётся с нуля при
-- первом же открытии приложения, хотя человек сидит с делом давно.
update tasks set taken_at = started_at where status = 'in_progress' and taken_at is null;
