-- Профиль человека: кто он и что закрывает (спека person-profile).
--
-- Колонка у членства, а не у человека: «что он закрывает» — это про его место в этой компании.
-- Вывели человека — профиль ушёл вместе с членством, чужих заметок о нём не осталось.
--
-- Свободный текст, а не анкета: анкета заставляет заполнять то, чего не знаешь, и устаревает молча.
-- Предел в 2000 знаков — чтобы профиль оставался абзацем, который читают, а не досье, которое листают.

alter table memberships add column about text check (about is null or length(about) <= 2000);

comment on column memberships.about is 'Профиль человека в этой компании: кто он и что закрывает (спека person-profile)';
