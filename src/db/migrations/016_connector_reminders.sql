-- Напоминание о неподключённом коннекторе (спека mcp-and-oauth, «Человек есть, коннектора нет»).
--
-- Владелец компании без коннектора — это компания, которая не работает: агент до неё не дотянется,
-- а Клод в разговоре будет выглядеть работающим, ничего не записывая. Первый клиент пилота так и
-- просидел сутки. Приветственное письмо уходит один раз и теряется в почте — нужен повтор.
--
-- Счёт по человеку, а не по компании: коннектор принадлежит человеку (oauth_tokens → user_id, без
-- org_id), один на все его компании. Считай мы письма по паре «компания + человек» — владелец трёх
-- компаний получил бы три письма в день об одном и том же коннекторе. Поэтому таблица лежит в
-- глобальном слое рядом с oauth_tokens и без RLS: она про человека, не про организацию.

create table connector_reminders (
  user_id uuid primary key references users(id) on delete cascade,
  sent_count integer not null default 0,
  last_sent_at timestamptz
);

comment on table connector_reminders is 'Сколько напоминаний о коннекторе ушло человеку и когда последнее (спека mcp-and-oauth)';
