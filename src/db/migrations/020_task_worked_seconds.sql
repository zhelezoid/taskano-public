-- Сколько всего человек проработал над делом (спека mini-app): сумма отрезков «Взять → остановился».
--
-- Таймер показывал время с последнего взятия: остановился и взялся снова — счёт начинался с нуля,
-- и потраченное за первый подход пропадало с экрана. Для дела, к которому возвращаются несколько
-- раз (а это обычное дело), счётчик врал тем сильнее, чем чаще человек переключался.
--
-- Отдельно от `time_entries`: там учёт времени, который человек ведёт сам кнопкой «Старт», и он
-- может считать иначе — например, включаться на встречу, не беря дело.
alter table tasks add column if not exists worked_seconds integer not null default 0;

comment on column tasks.worked_seconds is
  'Сумма отрезков работы по делу до текущего взятия, секунды (спека mini-app); идущий отрезок — от taken_at';
